// RC12 / SRS §11.9: one tagged link (and a printable QR) per channel, so every shared link is
// attributed on /insights. Writes docs/LINKS.md and docs/qr/*.svg. Run `pnpm links` (team-only output).
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { renderSVG } from "uqr";

const SITE = process.env.LINKS_SITE_URL ?? "https://ship-ai-sonoran-swap.vercel.app";
const ROOT = process.cwd();
const QR_DIR = path.join(ROOT, "docs", "qr");

type Channel = { src: string; where: string; path?: string; qr?: boolean };

const CHANNELS: Channel[] = [
  { src: "qr-screen", where: "QR shown on a presentation screen (also on /live)", qr: true },
  { src: "qr-table", where: "Printed QR card on our table", qr: true },
  { src: "linkedin", where: "Team LinkedIn launch posts" },
  { src: "x", where: "Posts on X" },
];

const url = (params: Record<string, string>, p = "/") => {
  const u = new URL(p, SITE);
  for (const [k, v] of Object.entries(params)) u.searchParams.set(k, v);
  return u.toString();
};

mkdirSync(QR_DIR, { recursive: true });
const rows: string[] = [];
for (const c of CHANNELS) {
  const link = url({ src: c.src }, c.path);
  let qr = "";
  if (c.qr) {
    writeFileSync(path.join(QR_DIR, `${c.src}.svg`), renderSVG(link, { border: 2, ecc: "M" }));
    qr = `[qr/${c.src}.svg](qr/${c.src}.svg)`;
  }
  rows.push(`| \`${c.src}\` | ${c.where} | ${link} | ${qr} |`);
}

// User tests: alternate headline variants; each tester gets their own code (FR-ANL-04, SRS §4.8).
const testers = Array.from({ length: 16 }, (_, i) => {
  const t = `T${String(i + 1).padStart(2, "0")}`;
  const v = i % 2 === 0 ? "a" : "b";
  return `| ${t} | ${v.toUpperCase()} | ${url({ src: "test", t, v })} |`;
});

const md = `# LINKS.md: Tagged links and QR codes

> Generated by \`pnpm links\` (scripts/links.ts) for ${SITE}. Every link the team shares must be one of these (QUALITY RC12, SRS §11.9), so /insights can attribute visits. The site reads \`src\` once and removes it from the address bar, so links people copy onward stay clean.

## Channels

| src | Where it's used | Link | QR |
|---|---|---|---|
${rows.join("\n")}

## User tests

Hand each tester the next unused code. Odd codes get headline A, even codes headline B. After the five-second test, note \`5s:pass\` or \`5s:fail\` in that tester's \`test_sessions.notes\`.

| Tester | Headline | Link |
|---|---|---|
${testers.join("\n")}

## Team devices

Open this once in every browser the team uses, so our own visits are excluded from /insights (FR-INS-13): ${url({ team: "1" })}

The flag is kept in that browser's local storage (no cookie) until you open ${url({ team: "0" })}. A private window starts without it, so open the team link there too.
`;

writeFileSync(path.join(ROOT, "docs", "LINKS.md"), md);
console.log(
  `links: ${CHANNELS.length} channels, ${CHANNELS.filter((c) => c.qr).length} QR codes, ${testers.length} tester links`,
);
